#!/usr/bin/env bash
# Collect the license text of every module linked into the roro binary
# into third_party/LICENSES.txt. Uses only the Go toolchain (no extra tools).
set -euo pipefail
cd "$(dirname "$0")/.."

out=third_party/LICENSES.txt
mkdir -p third_party
tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT

CGO_ENABLED=0 go build -o "$tmp" ./cmd/roro
{
  echo "Third-party software linked into the roro binary"
  echo "Generated by scripts/third-party-licenses.sh. Do not edit by hand."
  echo
  go version -m "$tmp" | awk '$1=="dep"{print $2, $3}' | while read -r mod ver; do
    dir=$(go mod download -json "$mod@$ver" | sed -n 's/.*"Dir": "\(.*\)".*/\1/p')
    lic=$(find "$dir" -maxdepth 1 -type f \( -iname 'LICENSE*' -o -iname 'COPYING*' -o -iname 'LICENCE*' \) | sort | head -1)
    echo "================================================================================"
    echo "$mod $ver"
    echo "================================================================================"
    if [[ -n "$lic" ]]; then
      cat "$lic"
    else
      echo "(no license file found at module root; see https://pkg.go.dev/$mod?tab=licenses)"
    fi
    echo
  done
} > "$out"
echo "wrote $out"
